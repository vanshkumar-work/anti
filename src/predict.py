"""Prediction and real-time inference service for ReviewGuard.

Provides single-review and batch-review prediction workflows
with probability estimates, text diagnostics, and explainability cues.
"""

import os
from typing import Any, Dict, Tuple
import joblib
import numpy as np
import pandas as pd
from sklearn.pipeline import Pipeline

from src.explainability import explain_single_prediction
from src.preprocessing import clean_text, extract_text_statistics

DEFAULT_PIPELINE_PATH = os.path.join("models", "reviewguard_pipeline.joblib")

CLASS_LABELS = {
    0: "More Similar to Truthful Examples",
    1: "Potentially Deceptive",
}

DISCLAIMER_TEXT = (
    "Academic Notice: Predictions generated by ReviewGuard are statistical model estimates "
    "based on linguistic patterns observed in the training corpus, not definitive legal proof of deception."
)


def load_pipeline(pipeline_path: str = DEFAULT_PIPELINE_PATH) -> Pipeline:
    """Load the trained ReviewGuard model pipeline from disk.

    Args:
        pipeline_path: Path to the serialized Joblib pipeline.

    Returns:
        Fitted scikit-learn Pipeline.

    Raises:
        FileNotFoundError: If the model file has not been generated yet.
    """
    if not os.path.exists(pipeline_path):
        raise FileNotFoundError(
            f"Trained model not found at '{pipeline_path}'. "
            "Please train the model first by running: python -m src.train"
        )
    pipeline = joblib.load(pipeline_path)
    return pipeline


def predict_single_review(
    pipeline: Pipeline,
    review_text: str,
) -> Dict[str, Any]:
    """Execute prediction and diagnostics for a single review string.

    Args:
        pipeline: Trained ReviewGuard pipeline.
        review_text: Text of the review to analyze.

    Returns:
        Structured dictionary containing prediction, scores, text diagnostics,
        explanation cues, and academic disclaimer.
    """
    # Validation for empty or whitespace-only input
    if not review_text or not str(review_text).strip():
        return {
            "is_valid": False,
            "error": "The input review is empty. Please enter review text to analyze.",
            "prediction_label": None,
            "disclaimer": DISCLAIMER_TEXT,
        }

    raw_text = str(review_text).strip()
    stats = extract_text_statistics(raw_text)

    # Check for extremely short input (less than 4 tokens)
    is_very_short = stats["word_count"] < 4

    cleaned = clean_text(raw_text)
    if not cleaned:
        return {
            "is_valid": False,
            "error": "The review contains only non-word characters or symbols.",
            "prediction_label": None,
            "disclaimer": DISCLAIMER_TEXT,
        }

    # Model inference
    pred_class_idx = int(pipeline.predict([raw_text])[0])
    prediction_label = CLASS_LABELS[pred_class_idx]

    # Probabilities / confidence calculation
    deceptive_prob = 0.5
    truthful_prob = 0.5
    confidence_pct = 50.0

    if hasattr(pipeline, "predict_proba"):
        probas = pipeline.predict_proba([raw_text])[0]
        truthful_prob = float(probas[0])
        deceptive_prob = float(probas[1])
        confidence_pct = round(max(truthful_prob, deceptive_prob) * 100, 2)
    elif hasattr(pipeline, "decision_function"):
        decision = float(pipeline.decision_function([raw_text])[0])
        confidence_pct = round(min(abs(decision) * 20 + 50, 99.0), 2)

    # Explainability cues
    explanations = explain_single_prediction(pipeline, raw_text, top_k=6)

    # Analytical summary message
    if pred_class_idx == 1:
        summary_msg = (
            f"The model detected stylistic patterns characteristic of deceptive opinion spam "
            f"with {confidence_pct}% estimated confidence. Noticeable promotional language or "
            f"abstract superlatives were identified."
        )
    else:
        summary_msg = (
            f"The model found text patterns aligning closely with authentic customer experiences "
            f"with {confidence_pct}% estimated confidence. Concrete spatial, logistical, or "
            f"balanced descriptive terms were observed."
        )

    if is_very_short:
        summary_msg += " (Warning: This review is exceptionally brief; linguistic confidence is limited.)"

    return {
        "is_valid": True,
        "input_text": raw_text,
        "predicted_class": pred_class_idx,
        "prediction_label": prediction_label,
        "is_deceptive": pred_class_idx == 1,
        "confidence_pct": confidence_pct,
        "deceptive_prob_pct": round(deceptive_prob * 100, 2),
        "truthful_prob_pct": round(truthful_prob * 100, 2),
        "text_statistics": stats,
        "explanation": explanations,
        "summary_message": summary_msg,
        "is_very_short": is_very_short,
        "disclaimer": DISCLAIMER_TEXT,
    }


def predict_batch_reviews(
    pipeline: Pipeline,
    df: pd.DataFrame,
    text_column: str,
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """Execute prediction on a batch of reviews from a DataFrame.

    Args:
        pipeline: Trained ReviewGuard pipeline.
        df: Input DataFrame containing review records.
        text_column: Column name containing the review strings.

    Returns:
        Tuple of (annotated_dataframe, batch_summary_dict).
    """
    if df is None or len(df) == 0:
        raise ValueError("The uploaded dataset is empty.")

    if text_column not in df.columns:
        raise ValueError(
            f"Selected column '{text_column}' was not found. "
            f"Available columns: {list(df.columns)}"
        )

    out_df = df.copy()

    # Handle missing or empty texts safely
    valid_mask = (
        out_df[text_column].notna()
        & (out_df[text_column].astype(str).str.strip().str.len() > 0)
    )

    valid_indices = out_df[valid_mask].index
    valid_texts = out_df.loc[valid_indices, text_column].astype(str).tolist()

    if len(valid_texts) == 0:
        raise ValueError("No valid non-empty review texts found in the selected column.")

    # Run predictions
    preds = pipeline.predict(valid_texts)

    # Probabilities
    if hasattr(pipeline, "predict_proba"):
        probas = pipeline.predict_proba(valid_texts)
        p_truthful = probas[:, 0]
        p_deceptive = probas[:, 1]
        confidence = np.max(probas, axis=1) * 100
    else:
        p_truthful = np.where(preds == 0, 0.8, 0.2)
        p_deceptive = np.where(preds == 1, 0.8, 0.2)
        confidence = np.full(len(preds), 80.0)

    # Populate result columns
    out_df["Predicted_Class"] = "Invalid / Empty Review"
    out_df["Confidence_Pct"] = np.nan
    out_df["Deceptive_Score_Pct"] = np.nan
    out_df["Truthful_Score_Pct"] = np.nan
    out_df["Word_Count"] = 0

    pred_labels = [CLASS_LABELS[int(p)] for p in preds]
    out_df.loc[valid_indices, "Predicted_Class"] = pred_labels
    out_df.loc[valid_indices, "Confidence_Pct"] = np.round(confidence, 1)
    out_df.loc[valid_indices, "Deceptive_Score_Pct"] = np.round(p_deceptive * 100, 1)
    out_df.loc[valid_indices, "Truthful_Score_Pct"] = np.round(p_truthful * 100, 1)
    out_df.loc[valid_indices, "Word_Count"] = [len(t.split()) for t in valid_texts]

    # Calculate summary metrics
    total_valid = len(valid_texts)
    deceptive_count = int((preds == 1).sum())
    truthful_count = int((preds == 0).sum())
    deceptive_pct = round((deceptive_count / total_valid) * 100, 1) if total_valid > 0 else 0.0
    truthful_pct = round((truthful_count / total_valid) * 100, 1) if total_valid > 0 else 0.0
    avg_confidence = round(float(np.mean(confidence)), 1) if total_valid > 0 else 0.0

    summary = {
        "total_rows": len(out_df),
        "valid_reviews_analyzed": total_valid,
        "invalid_or_empty_rows": len(out_df) - total_valid,
        "deceptive_count": deceptive_count,
        "truthful_count": truthful_count,
        "deceptive_pct": deceptive_pct,
        "truthful_pct": truthful_pct,
        "avg_confidence_pct": avg_confidence,
    }

    return out_df, summary
